#!/usr/bin/env python3
"""Episode pages for The Art of Everything.

Reads the podcast's RSS feed and writes:

  data/episodes.json        every episode as structured data
  episodes.html             the Episodes tab (whole back catalog)
  episodes/<slug>.html      one page per episode
  index.html                the newest episode and latest tracklist, between
                            the <!-- episodes:... --> markers
  sitemap.xml               every page, for search engines

Seasons are shown as sides of a record: season 1 is Side A, season 2 is
Side B, so episode 2.2 is "B2". Numbers come from the feed's itunes:season /
itunes:episode tags, or from the title ("Title | 2.2", "S1E10 Queen",
"S1 Finale - Post Malone").

The site's header and footer are copied from index.html (between the
<!-- shell:... --> markers), so a menu change made there carries over to the
generated pages on the next run.

Standard library only:

    python scraper/episodes.py
    python scraper/episodes.py --feed path/to/feed.xml   # offline, for testing
"""

