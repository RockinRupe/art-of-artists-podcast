def e(text: str) -> str:
    return html.escape(text or "", quote=True)


def extract_shell(index_html: str) -> tuple[str, str]:
    def between(name: str) -> str:
        m = re.search(rf"<!-- shell:{name}:start -->\n(.*?)\n\s*<!-- shell:{name}:end -->", index_html, re.S)
        if not m:
            raise ValueError(f"index.html is missing the shell:{name} markers")
        return m.group(1)
    return between("top"), between("bottom")


def shell_for(chunk: str, prefix: str) -> str:
    """Point the Episodes links at the current page and fix relative URLs
    for pages one folder down."""
    chunk = chunk.replace(' aria-current="page"', "")
    chunk = chunk.replace('href="episodes.html"', 'href="episodes.html" aria-current="page"')
    if prefix:
        chunk = re.sub(
            r'(href|src)="(?!https?:|#|mailto:|data:|/)([^"]*)"',
            lambda m: f'{m.group(1)}="{prefix}{m.group(2)}"',
            chunk,
        )
    return chunk


