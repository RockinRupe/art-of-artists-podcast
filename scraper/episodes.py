@dataclass
class Episode:
    guid: str
    slug: str
    title: str
    season: int | None
    number: int | None
    finale: bool
    bonus: bool             # an extra between numbered episodes ("Bonus" in the tracklist)
    trailer: bool           # the show's intro/trailer ("Intro")
    number_from: str        # where the number came from: "title", "tags", "order" or ""
    published: str | None   # ISO 8601
    duration_seconds: int | None
    audio_url: str
    image: str
    link: str
    summary: str
    notes_html: str

    # ----- display helpers -----
    @property
    def side(self) -> str:
        return chr(64 + self.season) if self.season else ""

    @property
    def code(self) -> str:
        if self.trailer:
            return "Intro"
        if self.bonus:
            return "Bonus"
        if not self.side:
            return "—"
        if self.finale:
            return f"{self.side}·FIN"
        return f"{self.side}{self.number}" if self.number is not None else self.side

    @property
    def where(self) -> str:
        if self.trailer:
            return "Show intro"
        if not self.side:
            return "Bonus track" if self.bonus else ""
        if self.bonus:
            return f"Side {self.side}, bonus track"
        if self.finale:
            return f"Side {self.side}, finale"
        if self.number is not None:
            return f"Side {self.side}, track {self.number}"
        return f"Side {self.side}"

    @property
    def date_label(self) -> str:
        if not self.published:
            return ""
        d = datetime.fromisoformat(self.published)
        return f"{d:%b} {d.day}, {d.year}"

    @property
    def date_iso(self) -> str:
        return self.published[:10] if self.published else ""

    @property
    def duration_label(self) -> str:
        if not self.duration_seconds:
            return ""
        minutes = round(self.duration_seconds / 60)
        if minutes < 60:
            return f"{max(minutes, 1)} min"
        return f"{minutes // 60} hr {minutes % 60} min"

    @property
    def iso_duration(self) -> str:
        s = self.duration_seconds or 0
        return f"PT{s // 3600}H{s % 3600 // 60}M{s % 60}S"

    @property
    def page(self) -> str:
        return f"episodes/{self.slug}.html"


