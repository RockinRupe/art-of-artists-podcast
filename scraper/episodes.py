def play_button(ep: Episode, prefix: str, css: str = "track-play", label: str = "") -> str:
    """A button that plays the episode in the site's own player. Falls back to
    a Spotify link if the feed has no audio file for it."""
    if not ep.audio_url:
        inner = label or PLAY_SVG
        return (f'<a class="{css}" href="{SPOTIFY_URL}" target="_blank" rel="noopener" '
                f'aria-label="Listen to {e(ep.title)} on Spotify">{inner}</a>')
    inner = label or PLAY_SVG
    aria = "" if label else f' aria-label="Play {e(ep.title)}"'
    return (f'<button class="{css}" type="button"{aria} data-play data-src="{e(ep.audio_url)}" '
            f'data-title="{e(ep.title)}" data-code="{e(ep.code)}" data-href="{prefix}{e(ep.page)}" '
            f'data-image="{e(ep.image)}">{inner}</button>')


def track_row(ep: Episode, prefix: str, latest: bool = False) -> str:
    meta = " · ".join(x for x in (ep.date_label, ep.duration_label) if x)
    search = f"{ep.code} {ep.title} {ep.summary}".lower()
    return f'''        <li class="track{" is-latest" if latest else ""}" data-season="{ep.season or 0}" data-search="{e(search)}">
          <span class="track-num">{e(ep.code)}</span>
          <div class="track-body">
            <h3 class="track-title"><a href="{prefix}{e(ep.page)}">{e(ep.title)}</a></h3>
            {f'<p class="track-desc">{e(ep.summary)}</p>' if ep.summary else ""}
          </div>
          <span class="track-date"><time datetime="{ep.date_iso}">{e(meta)}</time></span>
          {play_button(ep, prefix)}
        </li>'''


def title_class(ep: Episode) -> str:
    """Long titles get a smaller headline so they don't run to four lines."""
    return ' class="long-title"' if len(ep.title) > 28 else ""


def latest_block(ep: Episode) -> str:
    meta = " · ".join(x for x in ("New", ep.where, ep.date_label) if x)
    sticker = f"New · {ep.code}" if ep.side and not ep.bonus else "New"
    return f'''      <article class="latest" id="latest">
        <div class="latest-text">
          <p class="latest-meta">{e(meta)}</p>
          <h2{title_class(ep)}><a href="{e(ep.page)}">{e(ep.title)}</a></h2>
          <p class="latest-desc">{e(ep.summary)}</p>
          <div class="btn-row">
            {play_button(ep, "", "btn btn-play", "&#9654; Play episode")}
            <a class="btn" href="{SPOTIFY_URL}" target="_blank" rel="noopener">Spotify</a>
            <a class="btn" href="{APPLE_URL}" target="_blank" rel="noopener">Apple Podcasts</a>
          </div>
        </div>
        <div class="cover">
          <img src="{e(ep.image)}" alt="{SHOW_NAME} cover art" width="320" height="320" />
          <span class="sticker">{e(sticker)}</span>
        </div>
      </article>'''


def season_label(season: int | None) -> str:
    return f"Side {chr(64 + season)} · Season {season}" if season else "Extras"


def episodes_page(episodes: list[Episode], top: str, bottom: str) -> str:
    seasons: dict[int, list[Episode]] = {}
    for ep in episodes:
        seasons.setdefault(ep.season or 0, []).append(ep)
    order = sorted(seasons, key=lambda s: (s == 0, -s))  # newest season first, bonus last

    pills = ['<button type="button" data-season="all" aria-pressed="true">All</button>']
    groups = []
    for s in order:
        eps = seasons[s]
        years = sorted({ep.published[:4] for ep in eps if ep.published})
        span = f" · {years[0]}" + (f"–{years[-1][2:]}" if len(years) > 1 else "") if years else ""
        pills.append(f'<button type="button" data-season="{s}" aria-pressed="false">{e(season_label(s or None).split(" · ")[0] if s else "Extras")}{e(span)}</button>')
        count = f"{len(eps)} episode{'s' if len(eps) != 1 else ''}"
        rows = "\n".join(track_row(ep, "", latest=(ep is episodes[0])) for ep in eps)
        groups.append(f'''    <section class="season" data-season="{s}" aria-label="{e(season_label(s or None))}">
      <div class="section-label">
        <h2>{e(season_label(s or None))}</h2>
        <span class="eyebrow">{count}</span>
      </div>
      <ol class="tracklist">
{rows}
      </ol>
    </section>''')

    total = f"{len(episodes)} episode{'s' if len(episodes) != 1 else ''}"
    desc = "Every episode of The Art of Everything, newest first."
    jsonld = {
        "@context": "https://schema.org",
        "@type": "PodcastSeries",
        "name": SHOW_NAME,
        "url": SITE_URL,
        "webFeed": FEED_URL,
        "image": episodes[0].image if episodes else "",
    }
    return head("Episodes", desc, "episodes.html", "", episodes[0].image if episodes else "", jsonld=jsonld) \
        + shell_for(top, "") + f'''

  <main id="main" class="container">
    <section class="page-header">
      <p class="eyebrow">{total}</p>
      <h1>Episodes</h1>
      <p>The whole catalog, newest first. Press play on any episode to listen right here, or open it for the full show notes.</p>
    </section>

    <section class="episode-tools" aria-label="Find an episode">
      <div class="news-filters" role="group" aria-label="Filter by season" id="season-filters">
        {"".join(pills)}
      </div>
      <label class="search-field">
        <span class="eyebrow">Search</span>
        <input type="search" id="episode-search" placeholder="Artist, topic or title" autocomplete="off" />
      </label>
    </section>

    <div class="season-list" id="season-list">
{chr(10).join(groups)}
      <p class="news-empty" id="episodes-empty" hidden>No episodes match that search.</p>
    </div>
  </main>

''' + shell_for(bottom, "") + "\n"


def episode_page(ep: Episode, newer: Episode | None, older: Episode | None, top: str, bottom: str) -> str:
    p = "../"
    meta = " · ".join(x for x in (ep.where, ep.date_label, ep.duration_label) if x)
    description = ep.summary or f"An episode of {SHOW_NAME}."
    jsonld = {
        "@context": "https://schema.org",
        "@type": "PodcastEpisode",
        "name": ep.title,
        "url": SITE_URL + ep.page,
        "description": description,
        "datePublished": ep.date_iso or None,
        "timeRequired": ep.iso_duration if ep.duration_seconds else None,
        "image": ep.image or None,
        "episodeNumber": ep.number,
        "associatedMedia": {"@type": "MediaObject", "contentUrl": ep.audio_url} if ep.audio_url else None,
        "partOfSeason": {"@type": "PodcastSeason", "seasonNumber": ep.season} if ep.season else None,
        "partOfSeries": {"@type": "PodcastSeries", "name": SHOW_NAME, "url": SITE_URL},
    }
    jsonld = {k: v for k, v in jsonld.items() if v is not None}

    def neighbour(other: Episode | None, label: str, cls: str) -> str:
        if not other:
            return "<span></span>"
        return (f'<a class="{cls}" href="{e(other.slug)}.html"><span class="eyebrow">{label}</span>'
                f'<b>{e(other.code)} · {e(other.title)}</b></a>')

    notes = ep.notes_html or f"<p>{e(ep.summary)}</p>"
    return head(ep.title, description, ep.page, p, ep.image, og_type="article", jsonld=jsonld, audio=ep.audio_url) \
        + shell_for(top, p) + f'''

  <main id="main" class="container">
    <article class="episode-page">
      <header class="latest episode-hero">
        <div class="latest-text">
          <p class="latest-meta">{e(meta)}</p>
          <h1{title_class(ep)}>{e(ep.title)}</h1>
          <div class="btn-row">
            {play_button(ep, p, "btn btn-play", "&#9654; Play episode")}
            <a class="btn" href="{SPOTIFY_URL}" target="_blank" rel="noopener">Spotify</a>
            <a class="btn" href="{APPLE_URL}" target="_blank" rel="noopener">Apple Podcasts</a>
            <button class="btn" type="button" data-share data-url="{SITE_URL}{e(ep.page)}" data-title="{e(ep.title)}">Share</button>
          </div>
        </div>
        <div class="cover">
          <img src="{e(ep.image)}" alt="{SHOW_NAME} cover art" width="320" height="320" />
          {f'<span class="sticker">{e(ep.code)}</span>' if ep.code != "—" else ""}
        </div>
      </header>

      <section class="show-notes" aria-labelledby="notes-label">
        <div class="section-label"><h2 id="notes-label">Show notes</h2></div>
        <div class="notes-body">
          {notes}
        </div>
      </section>

      <nav class="episode-nav" aria-label="More episodes">
        {neighbour(older, "Previous episode", "prev")}
        {neighbour(newer, "Next episode", "next")}
      </nav>
      <p><a href="{p}episodes.html">&larr; All episodes</a></p>
    </article>
  </main>

''' + shell_for(bottom, p) + "\n"


def replace_between(text: str, name: str, new: str) -> str:
    pattern = re.compile(rf"(<!-- episodes:{name}:start -->\n).*?(\n\s*<!-- episodes:{name}:end -->)", re.S)
    if not pattern.search(text):
        raise ValueError(f"index.html is missing the episodes:{name} markers")
    return pattern.sub(lambda m: m.group(1) + new + m.group(2), text, count=1)


def sitemap(episodes: list[Episode]) -> str:
    today = datetime.now(timezone.utc).date().isoformat()
    urls = [("", today), ("episodes.html", episodes[0].date_iso if episodes else today),
            ("news.html", today), ("about.html", today)]
    urls += [(ep.page, ep.date_iso or today) for ep in episodes]
    body = "\n".join(f"  <url><loc>{SITE_URL}{e(path)}</loc><lastmod>{mod}</lastmod></url>" for path, mod in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'


