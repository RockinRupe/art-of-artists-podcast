def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def build(episodes: list[Episode], root: Path) -> list[str]:
    """Write every output file under `root`. Returns the paths that changed."""
    if not episodes:
        raise ValueError("Feed has no episodes; keeping the existing pages")
    index_path = root / "index.html"
    index_html = index_path.read_text(encoding="utf-8")
    top, bottom = extract_shell(index_html)
    changed: list[str] = []

    def out(rel: str, text: str) -> None:
        if write_if_changed(root / rel, text):
            changed.append(rel)

    data = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "feed": FEED_URL,
        "episodes": [{**asdict(ep), "code": ep.code, "page": ep.page} for ep in episodes],
    }
    # Only the timestamp changes on a quiet day; don't commit for that alone.
    old = root / "data" / "episodes.json"
    if old.exists():
        try:
            if json.loads(old.read_text(encoding="utf-8")).get("episodes") == data["episodes"]:
                data["generated_at"] = json.loads(old.read_text(encoding="utf-8"))["generated_at"]
        except (ValueError, KeyError):
            pass
    out("data/episodes.json", json.dumps(data, ensure_ascii=False, indent=2) + "\n")

    new_index = replace_between(index_html, "latest", latest_block(episodes[0]))
    new_index = replace_between(
        new_index, "list",
        "\n".join(track_row(ep, "", latest=(i == 0)) for i, ep in enumerate(episodes[:HOME_EPISODE_COUNT])),
    )
    out("index.html", new_index)
    out("episodes.html", episodes_page(episodes, top, bottom))

    keep = set()
    for i, ep in enumerate(episodes):
        newer = episodes[i - 1] if i > 0 else None
        older = episodes[i + 1] if i + 1 < len(episodes) else None
        out(ep.page, episode_page(ep, newer, older, top, bottom))
        keep.add(f"{ep.slug}.html")

    # Remove pages for episodes that left the feed (only ones we generated).
    ep_dir = root / "episodes"
    for page in ep_dir.glob("*.html"):
        if page.name not in keep and GENERATED_MARK in page.read_text(encoding="utf-8")[:400]:
            page.unlink()
            changed.append(f"episodes/{page.name} (removed)")

    out("sitemap.xml", sitemap(episodes))
    return changed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--feed", help="Read the feed from this file instead of the internet")
    ap.add_argument("--root", default=str(ROOT), help="Site folder to write into")
    args = ap.parse_args(argv)
    root = Path(args.root)

    try:
        raw = Path(args.feed).read_bytes() if args.feed else fetch(FEED_URL)
    except OSError as err:
        print(f"Could not read the podcast feed: {err}. Keeping the existing pages.", file=sys.stderr)
        return 1

    known = {}
    data_file = root / "data" / "episodes.json"
    if data_file.exists():
        try:
            known = {ep["guid"]: ep["slug"] for ep in json.loads(data_file.read_text(encoding="utf-8"))["episodes"]}
        except (ValueError, KeyError):
            pass

    try:
        episodes = parse_feed(raw, known)
        changed = build(episodes, root)
    except (ET.ParseError, ValueError) as err:
        print(f"Could not build episode pages: {err}", file=sys.stderr)
        return 1

    print(f"{len(episodes)} episodes. " + (f"Updated: {', '.join(changed)}" if changed else "Nothing changed."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
