def fetch(url: str, timeout: float = 30) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read()


def parse_duration(raw: str | None) -> int | None:
    """itunes:duration is either seconds ("2534") or "H:MM:SS" / "MM:SS"."""
    if not raw:
        return None
    raw = raw.strip()
    try:
        if ":" in raw:
            seconds = 0
            for part in raw.split(":"):
                seconds = seconds * 60 + int(float(part))
            return seconds
        return int(float(raw))
    except ValueError:
        return None


def parse_numbering(title: str, season: int | None, number: int | None):
    """Return (clean title, season, number, finale) from a raw episode title."""
    title = title.strip()
    finale = False
    if m := re.match(r"^(.*?)\s*\|\s*(\d+)\.(\d+)\s*$", title):
        title = m.group(1)
        season = season or int(m.group(2))
        number = number or int(m.group(3))
    elif m := re.match(r"^S(\d+)E(\d+)\s*[-–:]?\s*(.+)$", title, re.I):
        season = season or int(m.group(1))
        number = number or int(m.group(2))
        title = m.group(3)
    elif m := re.match(r"^S(\d+)\s+Finale\s*[-–:]\s*(.+)$", title, re.I):
        season = season or int(m.group(1))
        finale = number is None
        title = f"Season {m.group(1)} Finale: {m.group(2)}"
    return title.strip(), season, number, finale


def fill_missing_numbers(episodes: list[Episode]) -> None:
    """Give unnumbered episodes a place on the record. `episodes` is newest first.

    An episode with no season or number belongs to the same season as the one
    before it. If that one was track N and nothing else is numbered N+1, it
    becomes track N+1 (B2 then B3). Otherwise it's a bonus track, so specials
    released between numbered episodes never take another episode's number."""
    # Two episodes can claim the same number (one in its title, another in
    # the host's episode tags). A number written in the title wins, then the
    # later release; the other one becomes a bonus track.
    claims: dict[tuple, list[Episode]] = {}
    for ep in episodes:
        if ep.season and ep.number is not None:
            claims.setdefault((ep.season, ep.number), []).append(ep)
    for eps in claims.values():
        if len(eps) > 1:
            eps.sort(key=lambda x: (x.number_from == "title", x.published or ""), reverse=True)
            for loser in eps[1:]:
                loser.number, loser.bonus, loser.number_from = None, True, ""

    taken = {(e.season, e.number) for e in episodes if e.season and e.number is not None}
    for i in range(len(episodes) - 2, -1, -1):
        ep, older = episodes[i], episodes[i + 1]
        if ep.trailer or ep.finale or ep.season is not None or ep.number is not None:
            continue
        if older.season is None:
            continue
        ep.season = older.season
        nxt = (older.season, older.number + 1) if older.number is not None else None
        if not ep.bonus and nxt and nxt not in taken:
            ep.number = nxt[1]
            ep.number_from = "order"
            taken.add(nxt)
        else:
            ep.bonus = True


def plain_text(raw_html: str) -> str:
    raw_html = re.sub(r"<(script|style)\b.*?</\1\s*>", " ", raw_html, flags=re.I | re.S)
    text = re.sub(r"<(br|/p|/li)[^>]*>", " ", raw_html, flags=re.I)
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def make_summary(raw_html: str, limit: int = 240) -> str:
    text = plain_text(raw_html)
    # Anchor appends a "--- Send in a voice message: …" footer to descriptions.
    text = re.split(r"\s*-{3,}(?:\s|$)", text)[0].strip()
    if len(text) > limit:
        text = text[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:.") + "…"
    return text


def slugify(title: str) -> str:
    s = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    if len(s) > 60:
        s = s[:60].rsplit("-", 1)[0]
    return s or "episode"


class _Sanitizer(HTMLParser):
    """Keeps a small set of formatting tags from show notes and drops the rest.
    Links keep only http(s) hrefs and always open in a new tab."""

    ALLOWED = {"p", "br", "a", "strong", "b", "em", "i", "ul", "ol", "li"}
    VOID = {"br"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.out: list[str] = []
        self.open: list[str] = []
        self.skip = 0  # inside <script>/<style>

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1
            return
        if tag not in self.ALLOWED or self.skip:
            return
        if tag == "a":
            href = dict(attrs).get("href") or ""
            if not re.match(r"^https?://", href, re.I):
                self.out.append("<a>")
            else:
                self.out.append(f'<a href="{html.escape(href, quote=True)}" target="_blank" rel="noopener">')
        else:
            self.out.append(f"<{tag}>")
        if tag not in self.VOID:
            self.open.append(tag)

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip = max(0, self.skip - 1)
            return
        if tag in self.ALLOWED and tag in self.open and not self.skip:
            while self.open:
                t = self.open.pop()
                self.out.append(f"</{t}>")
                if t == tag:
                    break

    def handle_data(self, data):
        if not self.skip:
            self.out.append(html.escape(data, quote=False))

    def result(self) -> str:
        while self.open:
            self.out.append(f"</{self.open.pop()}>")
        return "".join(self.out).strip()


def sanitize_notes(raw_html: str) -> str:
    if "<" not in raw_html:  # plain text: keep the paragraphs
        paras = [p.strip() for p in re.split(r"\n\s*\n", raw_html) if p.strip()]
        return "".join(f"<p>{html.escape(p)}</p>" for p in paras)
    s = _Sanitizer()
    s.feed(raw_html)
    s.close()
    return re.sub(r"(<p>\s*</p>)+", "", s.result())


def parse_feed(xml_bytes: bytes, known_slugs: dict[str, str] | None = None) -> list[Episode]:
    """Episodes newest first. `known_slugs` maps guid -> slug from the last
    run, so an episode keeps its URL even if its title is edited later."""
    known_slugs = known_slugs or {}
    root = ET.fromstring(xml_bytes)
    channel = root.find("channel")
    if channel is None:
        raise ValueError("Feed has no <channel>")

    show_image = ""
    if (img := channel.find("itunes:image", NS)) is not None:
        show_image = img.get("href", "")
    elif (url := channel.findtext("image/url")) is not None:
        show_image = url.strip()

    episodes: list[Episode] = []
    used: set[str] = set(known_slugs.values())
    for item in channel.findall("item"):
        raw_title = (item.findtext("title") or "Untitled episode").strip()
        season = _int(item.findtext("itunes:season", namespaces=NS))
        number = _int(item.findtext("itunes:episode", namespaces=NS))
        tagged = number is not None
        title, season, number, finale = parse_numbering(raw_title, season, number)
        number_from = ("tags" if tagged else "title") if number is not None else ""
        kind = (item.findtext("itunes:episodeType", namespaces=NS) or "").strip().lower()
        trailer = kind == "trailer" or bool(re.match(r"^(intro|trailer)\b", title, re.I))
        bonus = not trailer and (kind == "bonus" or bool(re.match(r"^bonus\b", title, re.I)))
        if trailer or bonus:
            number = None
            number_from = ""
            if trailer:
                season = None

        published = None
        if pub := item.findtext("pubDate"):
            try:
                published = parsedate_to_datetime(pub).astimezone(timezone.utc).isoformat()
            except (TypeError, ValueError):
                pass

        enclosure = item.find("enclosure")
        audio = enclosure.get("url", "") if enclosure is not None else ""
        image_el = item.find("itunes:image", NS)
        image = image_el.get("href", "") if image_el is not None else ""
        notes = item.findtext("content:encoded", namespaces=NS) or item.findtext("description") or ""
        guid = (item.findtext("guid") or audio or raw_title).strip()
        link = (item.findtext("link") or "").strip()

        slug = known_slugs.get(guid)
        if not slug:
            base = slug = slugify(title)
            n = 2
            while slug in used:
                slug = f"{base}-{n}"
                n += 1
            used.add(slug)

        episodes.append(Episode(
            guid=guid,
            slug=slug,
            title=title,
            season=season,
            number=number,
            finale=finale,
            bonus=bonus,
            trailer=trailer,
            number_from=number_from,
            published=published,
            duration_seconds=parse_duration(item.findtext("itunes:duration", namespaces=NS)),
            audio_url=audio if re.match(r"^https?://", audio) else "",
            image=image or show_image,
            link=link if re.match(r"^https?://", link) else "",
            summary=make_summary(notes),
            notes_html=sanitize_notes(notes),
        ))

    episodes.sort(key=lambda e: e.published or "", reverse=True)
    fill_missing_numbers(episodes)
    return episodes


def _int(raw: str | None) -> int | None:
    try:
        return int(raw.strip()) if raw else None
    except ValueError:
        return None


